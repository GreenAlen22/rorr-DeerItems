local function spawn_drone_copy(src, x, y, owner, hp_frac, lineage)
    -- Р ВРЎРѓРЎвЂљР С‘Р Р…Р Р…РЎвЂ№Р в„– Р С‘Р Р…Р Т‘Р ВµР С”РЎРѓ Р С•Р В±РЎР‰Р ВµР С”РЎвЂљР В° (Р С”Р С•РЎР‚РЎР‚Р ВµР С”РЎвЂљР Р…Р С• РЎР‚Р В°Р В±Р С•РЎвЂљР В°Р ВµРЎвЂљ Р С‘ Р Т‘Р В»РЎРЏ Р С”Р В°РЎРѓРЎвЂљР С•Р СР Р…РЎвЂ№РЎвЂ¦ Р СР С•Р Т‘Р С•Р Р†РЎвЂ№РЎвЂ¦ Р Т‘РЎР‚Р С•Р Р…Р С•Р Р†)
    local obj
    local ok = pcall(function() obj = src:get_object_index_self() end)
    if not ok or not obj then obj = src.object_index end

    local inst = Instance.wrap(gm.instance_create(x, y, obj))
    if not inst:exists() then return nil end
    g_spawned[inst.id] = lineage or "dup"   -- Р В»Р С‘Р Р…Р С‘РЎРЏ Р Т‘РЎР‚Р С•Р Р…Р В°: "orig" (Р С—РЎР‚Р С•Р Т‘Р С•Р В»Р В¶Р ВµР Р…Р С‘Р Вµ Р С”РЎС“Р С—Р В»Р ВµР Р…Р Р…Р С•Р С–Р С•) Р С‘Р В»Р С‘ "dup" (Р С”Р С•Р С—Р С‘РЎРЏ)

    -- Р СџРЎР‚Р С‘Р Р†РЎРЏР В·Р С”Р В° Р С” Р Р†Р В»Р В°Р Т‘Р ВµР В»РЎРЉРЎвЂ РЎС“ (Р С—Р В°РЎвЂљРЎвЂљР ВµРЎР‚Р Р… Р С‘Р В· Р С—РЎР‚Р С‘Р СР ВµРЎР‚Р В° РЎвЂљРЎС“РЎР‚Р ВµР В»Р С‘ РЎвЂљРЎС“Р В»Р С”Р С‘РЎвЂљР В°)
    inst.parent = owner
    inst.master = owner
    inst.team   = owner.team
    if owner.level then inst.level = owner.level end

    -- Р СљР ВµРЎвЂљР С”Р В° Р’В«РЎРѓР С•Р В·Р Т‘Р В°Р Р…Р С• Р Р…Р В°Р СР С‘Р’В» РІР‚вЂќ РЎвЂЎРЎвЂљР С•Р В±РЎвЂ№ Р С—Р С•Р В»Р В»Р С‘Р Р…Р С– Р С—Р С•Р С”РЎС“Р С—Р С•Р С” Р Р…Р Вµ Р С—РЎР‚Р С‘Р Р…РЎРЏР В» Р С”Р С•Р С—Р С‘РЎР‹ Р В·Р В° Р Р…Р С•Р Р†РЎС“РЎР‹ Р С—Р С•Р С”РЎС“Р С—Р С”РЎС“
    -- Р С‘ Р Р…Р Вµ Р В·Р В°Р С—РЎС“РЎРѓРЎвЂљР С‘Р В» Р В±Р ВµРЎРѓР С”Р С•Р Р…Р ВµРЎвЂЎР Р…Р С•Р Вµ РЎРѓР В°Р СР С•Р Т‘РЎС“Р В±Р В»Р С‘РЎР‚Р С•Р Р†Р В°Р Р…Р С‘Р Вµ.
    inst:get_data("DeerItems", GUID).assembly_spawned = true

    pcall(function() inst:recalculate_stats() end)

    -- Р СџР С•Р Р…Р С‘Р В¶Р ВµР Р…Р Р…Р С•Р Вµ HP Р Т‘Р В»РЎРЏ Р Р†Р С•РЎРѓРЎРѓРЎвЂљР В°Р Р…Р С•Р Р†Р В»Р ВµР Р…Р Р…РЎвЂ№РЎвЂ¦ (Р В±Р В°Р В»Р В°Р Р…РЎРѓ: Р В°РЎР‚Р СР С‘РЎРЏ Р Р…Р Вµ РЎРѓРЎвЂљР В°Р Р…Р С•Р Р†Р С‘РЎвЂљРЎРѓРЎРЏ Р В±Р ВµРЎРѓРЎРѓР СР ВµРЎР‚РЎвЂљР Р…Р С•Р в„–)
    if hp_frac and inst.maxhp then
        inst.hp = math.max(1, inst.maxhp * hp_frac)
    end

    return inst
end

-- Р вЂєР С•Р С–Р С‘Р С”Р В° Р С—РЎР‚Р ВµР Т‘Р СР ВµРЎвЂљР В°
-- Р СџРЎР‚Р С‘ Р С—Р С•Р В»РЎС“РЎвЂЎР ВµР Р…Р С‘Р С‘ Р С—РЎР‚Р ВµР Т‘Р СР ВµРЎвЂљР В° Р С—Р ВµРЎР‚Р ВµРЎРѓР ВµР С‘Р Р†Р В°Р ВµР С Р В±Р В°Р В·Р С•Р Р†РЎвЂ№Р в„– Р Р…Р В°Р В±Р С•РЎР‚ Р Т‘РЎР‚Р С•Р Р…Р С•Р Р† Р Т‘Р В»РЎРЏ РЎРЊРЎвЂљР С•Р С–Р С• Р Р†Р В»Р В°Р Т‘Р ВµР В»РЎРЉРЎвЂ Р В°,
