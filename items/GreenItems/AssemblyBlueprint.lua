-- Р СџР С•Р В»Р В»Р С‘Р Р…Р С– Р С—Р С•Р С”РЎС“Р С—Р С•Р С”: Р С‘РЎвЂ°Р ВµР С Р Р…Р С•Р Р†РЎвЂ№РЎвЂ¦ РЎРѓР С•РЎР‹Р В·Р Р…РЎвЂ№РЎвЂ¦ Р Т‘РЎР‚Р С•Р Р…Р С•Р Р† Р С‘ Р С”Р В°РЎвЂљР С‘Р С Р Т‘РЎС“Р В±Р В»Р С‘РЎР‚Р С•Р Р†Р В°Р Р…Р С‘Р Вµ.
local function poll_owner_drones(actor, stack)
    if stack <= 0 then return end

    -- Р РЋР С—Р В°Р Р†Р Р… РІР‚вЂќ РЎвЂљР С•Р В»РЎРЉР С”Р С• Р Р…Р В° РЎвЂ¦Р С•РЎРѓРЎвЂљР Вµ
    local state = g_owner_state[actor.id]
    if not state then
        state = { known = {}, started = false, last_poll = -1 }
        g_owner_state[actor.id] = state
    end

    local frame = Global._current_frame
    if frame == state.last_poll then return end
    if frame % POLL_PERIOD ~= 0 then return end
    state.last_poll = frame

    -- Р РЋР Р…Р В°РЎвЂЎР В°Р В»Р В° Р В±Р ВµРЎР‚РЎвЂР С РЎРѓР С•РЎР‹Р В·Р Р…Р С‘Р С”Р С•Р Р† Р С—Р С• Р С”Р С•Р СР В°Р Р…Р Т‘Р Вµ, Р В·Р В°РЎвЂљР ВµР С Р Р…Р С‘Р В¶Р Вµ Р С•РЎРѓРЎвЂљР В°Р Р†Р В»РЎРЏР ВµР С РЎвЂљР С•Р В»РЎРЉР С”Р С• Р Т‘РЎР‚Р С•Р Р…Р С•Р Р† РЎРЊРЎвЂљР С•Р С–Р С• Р Р†Р В»Р В°Р Т‘Р ВµР В»РЎРЉРЎвЂ Р В°.
    local found = List.wrap(actor:find_characters_circle(actor.x, actor.y, FIND_RADIUS, false, actor.team, true))

    local seen = {}
    for _, char in ipairs(found) do
        local owner = drone_owner(char)
        if char.object_index ~= oP and not is_not_drone(char) and same_instance(owner, actor) then              -- Р С‘Р С–РЎР‚Р С•Р С”Р С•Р Р† Р Р…Р Вµ РЎвЂљРЎР‚Р С•Р С–Р В°Р ВµР С
            local id = char.id
            seen[id] = true

            if not state.known[id] then
                -- Р вЂќРЎР‚Р С•Р Р…, Р С”Р С•РЎвЂљР С•РЎР‚Р С•Р С–Р С• Р СРЎвЂ№ РЎР‚Р В°Р Р…РЎРЉРЎв‚¬Р Вµ Р Р…Р Вµ Р Р†Р С‘Р Т‘Р ВµР В»Р С‘
                if state.started and not g_spawned[id] then
                    -- Р СњР В°РЎРѓРЎвЂљР С•РЎРЏРЎвЂ°Р В°РЎРЏ Р С—Р С•Р С”РЎС“Р С—Р С”Р В° РІвЂ вЂ™ РЎР‚Р С•Р В»Р В» Р Т‘РЎС“Р В±Р В»Р С‘РЎР‚Р С•Р Р†Р В°Р Р…Р С‘РЎРЏ
                    if math.random() < hyper_chance(DUP_PER_STACK, stack, DUP_CAP) then
                        spawn_drone_copy(char, char.x, char.y, owner, nil, "dup")  -- Р Т‘РЎС“Р В±Р В»Р С‘Р С”Р В°РЎвЂљ Р С—Р С•Р С”РЎС“Р С—Р С”Р С‘ (Р В»Р С‘Р Р…Р С‘РЎРЏ "dup"), Р С—Р С•Р В»Р Р…Р С•Р Вµ HP
                    end
                end
                -- (Р ВµРЎРѓР В»Р С‘ Р В±Р В°Р В·Р В° Р ВµРЎвЂ°РЎвЂ Р Р…Р Вµ Р В·Р В°РЎРѓР ВµРЎРЏР Р…Р В° РІР‚вЂќ Р С—РЎР‚Р С•РЎРѓРЎвЂљР С• Р В·Р В°Р С—Р С•Р СР С‘Р Р…Р В°Р ВµР С, Р В±Р ВµР В· РЎР‚Р С•Р В»Р В»Р В°)
            end
        end
    end

    state.known = seen          -- Р В·Р В°Р СР ВµР Р…РЎРЏР ВµР С Р Р…Р В°Р В±Р С•РЎР‚, Р С•РЎвЂљРЎРѓР ВµР С‘Р Р†Р В°РЎРЏ Р С‘РЎРѓРЎвЂЎР ВµР В·Р Р…РЎС“Р Р†РЎв‚¬Р С‘Р Вµ id
    state.started = true
end

