-- Р Р€Р В¶Р Вµ Р Р†Р С‘Р Т‘Р ВµР Р…Р Р…РЎвЂ№Р Вµ Р’В«РЎРѓР В»Р С•Р СРЎвЂ№Р’В» (РЎРѓРЎвЂљР В°РЎР‚РЎвЂ№Р в„– Р С•РЎР‚Р С‘Р С–Р С‘Р Р…Р В°Р В»РЎРЉРЎРѓР С”Р С‘Р в„–, РЎвЂЎРЎС“Р В¶Р С‘Р Вµ) Р Р…Р Вµ РЎвЂљРЎР‚Р С•Р С–Р В°Р ВµР С Р Р…Р С‘Р С”Р С•Р С–Р Т‘Р В° РІР‚вЂќ РЎРЊРЎвЂљР С• РЎС“Р В±Р С‘РЎР‚Р В°Р ВµРЎвЂљ Р Т‘РЎР‹Р С—РЎвЂ№ Р С•РЎвЂљ
-- Р С—РЎС“РЎвЂљР В°Р Р…Р С‘РЎвЂ РЎвЂ№ Р’В«Р С”Р В°Р С”Р С•Р в„– РЎРѓР В»Р С•Р С РЎвЂЎР ВµР в„–Р’В».
Callback.add(Callback.ON_STEP, function()
    if Net.client then return end

    local nowf = Global._current_frame or 0

    -- Р РЋР Р…Р С‘Р СР С•Р С” РЎвЂљР ВµР С”РЎС“РЎвЂ°Р С‘РЎвЂ¦ Р’В«РЎРѓР В»Р С•Р СР С•Р Р†Р’В» + РЎвЂћР С‘Р С”РЎРѓР С‘РЎР‚РЎС“Р ВµР С Р С”Р В°Р Т‘РЎР‚ Р С—Р ВµРЎР‚Р Р†Р С•Р С–Р С• Р С—Р С•РЎРЏР Р†Р В»Р ВµР Р…Р С‘РЎРЏ Р С”Р В°Р В¶Р Т‘Р С•Р С–Р С•
    local brokens = Instance.find_all(DRONE_INTERACT)
    local cur = {}
    for _, it in ipairs(brokens) do
        if Instance.exists(it) then
            cur[it.id] = true
            if not g_broken_seen[it.id] then
                g_broken_seen[it.id] = nowf
            end
        end
    end
    -- Р вЂ”Р В°Р В±РЎвЂ№Р Р†Р В°Р ВµР С Р С‘РЎРѓРЎвЂЎР ВµР В·Р Р…РЎС“Р Р†РЎв‚¬Р С‘Р Вµ Р’В«РЎРѓР В»Р С•Р СРЎвЂ№Р’В»
    for id in pairs(g_broken_seen) do
        if not cur[id] then g_broken_seen[id] = nil end
    end

    -- Р СљР ВµРЎвЂљР С”Р С‘: Р С”Р В°Р В¶Р Т‘Р В°РЎРЏ РЎРѓР Р…Р С•РЎРѓР С‘РЎвЂљ Р С›Р вЂќР ВР Сњ Р’В«РЎРѓР В»Р С•Р СР’В» РЎР‚РЎРЏР Т‘Р С•Р С, Р С—Р С•РЎРЏР Р†Р С‘Р Р†РЎв‚¬Р С‘Р в„–РЎРѓРЎРЏ Р СњР вЂў Р В Р С’Р СњР В¬Р РЃР вЂў РЎРѓР В°Р СР С•Р в„– Р С–Р С‘Р В±Р ВµР В»Р С‘; Р В·Р В°РЎвЂљР ВµР С Р С–Р В°РЎРѓР Р…Р ВµРЎвЂљ.
    for mi = #g_revive_marks, 1, -1 do
        local m = g_revive_marks[mi]
        local done = (nowf > m.expires)        -- Р СР ВµРЎвЂљР С”Р В° Р С‘РЎРѓРЎвЂљР ВµР С”Р В»Р В° РІР‚вЂќ РЎРѓР Р…РЎРЏРЎвЂљРЎРЉ
        if not done then
            for _, it in ipairs(brokens) do
                if Instance.exists(it)
                   and (g_broken_seen[it.id] or nowf) >= m.created          -- Р’В«РЎРѓР В»Р С•Р СР’В» Р С•РЎвЂљ Р В­Р СћР С›Р в„ў Р С–Р С‘Р В±Р ВµР В»Р С‘, Р Р…Р Вµ Р В»Р ВµР В¶Р В°Р Р†РЎв‚¬Р С‘Р в„– РЎР‚Р В°Р Р…РЎРЉРЎв‚¬Р Вµ
                   and gm.point_distance(m.x, m.y, it.x, it.y) < CLEAN_RADIUS then
                    it:destroy()
                    g_broken_seen[it.id] = nil
                    done = true
                    break
                end
            end
        end
        if done then table.remove(g_revive_marks, mi) end
    end
end)
