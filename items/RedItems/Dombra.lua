    if Instance.exists(actor) then
        actor:sound_play(sound, volume, pitch)
    end
end)

-- guid РјРѕРґР° РІС‹РЅРѕСЃРёРј РѕРґРёРЅ СЂР°Р· вЂ” РґР»СЏ per-actor РєСѓР»РґР°СѓРЅР° СЃСЂР°Р±Р°С‚С‹РІР°РЅРёСЏ
