local item = Item.new("Dombra")
item:set_sprite(sprite)
item:set_tier(ItemTier.RARE)
item.loot_tags = Item.LootTag.CATEGORY_DAMAGE

-- РћС‡РёСЃС‚РєР° РІСЃРµС… РєРѕР»Р»Р±РµРєРѕРІ РїРµСЂРµРґ РїРµСЂРµРѕРїСЂРµРґРµР»РµРЅРёРµРј
-- РџСЂРё РїРѕРїР°РґР°РЅРёРё Р°С‚Р°РєРѕР№: С€Р°РЅСЃ 20% РїСЂРёР·РІР°С‚СЊ РєСЂС‹Р»СЊСЏ Р±РµСЂРєСѓС‚Р° СЃР»РµРІР° Рё СЃРїСЂР°РІР°
DeerItemsCallbacks.item_attack_hit(item, function(actor, victim, stack, attack_info)
    if Net.client then return end

    -- РђРЅС‚Рё-РЅР°Р»РѕР¶РµРЅРёРµ: onAttackHit Р·РѕРІС‘С‚СЃСЏ РЅР° РљРђР–Р”РћР• РїРѕРїР°РґР°РЅРёРµ (РјРЅРѕРіРѕС†РµР»РµРІС‹Рµ/С‡Р°СЃС‚С‹Рµ Р°С‚Р°РєРё Р·Р° РєР°РґСЂ
    -- РґР°СЋС‚ РїР°С‡РєСѓ РЅР°Р»РѕР¶РµРЅРЅС‹С… Р·РІСѓРєРѕРІ). РќРµ С‡Р°С‰Рµ РѕРґРЅРѕРіРѕ СЃСЂР°Р±Р°С‚С‹РІР°РЅРёСЏ СЂР°Р· РІ PROC_COOLDOWN РєР°РґСЂРѕРІ.
    local data  = actor:get_data("DeerItems", GUID)
    local frame = Global._current_frame
    if data.dombra_last and (frame - data.dombra_last) < PROC_COOLDOWN then return end

    -- РџР»РѕСЃРєРёР№ С€Р°РЅСЃ 20% (РЅРµ Р·Р°РІРёСЃРёС‚ РѕС‚ РєРѕР»РёС‡РµСЃС‚РІР° СЃС‚Р°РєРѕРІ)
    if math.random() >= 0.20 then return end
    data.dombra_last = frame

    -- Р—РІСѓРє СЃСЂР°Р±Р°С‚С‹РІР°РЅРёСЏ: СЃР»СѓС‡Р°Р№РЅР°СЏ РіСЂРѕРјРєРѕСЃС‚СЊ (0.8вЂ“1.2) Рё РІС‹СЃРѕС‚Р° С‚РѕРЅР°/РёРЅС‚РѕРЅР°С†РёСЏ (0.8вЂ“1.3)
    local sound_volume = 0.8 + math.random() * 0.4
    local sound_pitch = 0.8 + math.random() * 0.5
    actor:sound_play(sound, sound_volume, sound_pitch)

    -- Р’ РѕРґРёРЅРѕС‡РЅРѕР№ РёРіСЂРµ Net.host С‚РѕР¶Рµ РІРѕР·РІСЂР°С‰Р°РµС‚ true, РѕРґРЅР°РєРѕ
    -- send_to_all СЂР°Р·СЂРµС€С‘РЅ С‚РѕР»СЊРєРѕ СЃРµС‚РµРІРѕРјСѓ С…РѕСЃС‚Сѓ.
    if Net.host then
        packet_sound:send_to_all(actor, sound_volume, sound_pitch)
    end

    -- Р’РёР·СѓР°Р»: РѕРґРЅРё Р±РѕР»СЊС€РёРµ РєСЂС‹Р»СЊСЏ Р±РµСЂРєСѓС‚Р° СЂР°СЃРїР°С…РёРІР°СЋС‚СЃСЏ Р—Рђ СЃРїРёРЅРѕР№ РёРіСЂРѕРєР°
    local wing = oWing:create(actor.x, actor.y - WING_Y_OFFSET)
    wing.parent = actor
    wing.depth  = actor.depth + 1

    -- "РћР‘Р©РР™ СѓСЂРѕРЅ": Р±Р°Р·РѕРІС‹Р№ СѓСЂРѕРЅ СЃСЂР°Р±РѕС‚Р°РІС€РµРіРѕ СѓРґР°СЂР° (Р±РµР· РєСЂРёС‚Р°)
    local base_damage = attack_info:get_damage_nocrit()
    -- РЎСѓРјРјР°СЂРЅРѕ РѕР±Р° РєСЂС‹Р»Р°: 122% +122% Р·Р° СЃС‚Р°Рє в†’ РїРѕ 61% РЅР° РєР°Р¶РґРѕРµ РєСЂС‹Р»Рѕ
    local dmg = base_damage * 0.61 * stack

    -- Р‘СЊС‘Рј РІР·СЂС‹РІРѕРј СЃ РєР°Р¶РґРѕР№ СЃС‚РѕСЂРѕРЅС‹ РёРіСЂРѕРєР° (РІРёР·СѓР°Р» вЂ” РѕР±С‰РёРµ РєСЂС‹Р»СЊСЏ Р·Р° СЃРїРёРЅРѕР№, СЃРїСЂР°Р№С‚ РІР·СЂС‹РІР° РЅРµ РЅСѓР¶РµРЅ)
    for _, dir in ipairs({-1, 1}) do
        local inst = actor:fire_explosion(
            actor.x + HIT_OFFSET * dir,       -- СЃР»РµРІР° (-) Рё СЃРїСЂР°РІР° (+) РѕС‚ РёРіСЂРѕРєР°
            actor.y,
            HIT_W, HIT_H,                     -- Р·РѕРЅР° РїРѕСЂР°Р¶РµРЅРёСЏ РєСЂС‹Р»Р°
            dmg,                              -- СѓСЂРѕРЅ РєСЂС‹Р»Р°
            nil,                              -- СЃРїСЂР°Р№С‚ РІР·СЂС‹РІР°
            nil,                              -- СЃРїСЂР°Р№С‚ СЌС„С„РµРєС‚Р° РїСЂРё РїРѕРїР°РґР°РЅРёРё (РЅРµ РЅСѓР¶РµРЅ вЂ” РІРёР·СѓР°Р» РѕР±С‰РёР№)
            false                             -- Р±РµР· proc-РєРѕСЌС„С„РёС†РёРµРЅС‚Р°
        )

        -- РќР°СЃС‚СЂРѕР№РєР° СѓСЂРѕРЅР° РєСЂС‹Р»Р°:
        -- proc = false РћР‘РЇР—РђРўР•Р›Р¬РќРћ вЂ” РёРЅР°С‡Рµ РїРѕРїР°РґР°РЅРёРµ РєСЂС‹Р»Р° СЃРЅРѕРІР° РІС‹Р·РѕРІРµС‚ onAttackHit
        -- Рё Р·Р°РїСѓСЃС‚РёС‚ РЅРѕРІС‹Рµ РєСЂС‹Р»СЊСЏ в†’ Р±РµСЃРєРѕРЅРµС‡РЅС‹Р№ СЃР°РјРѕРїСЂРѕРє.
        local ai = inst.attack_info
        ai:set_critical(false)                -- РєСЂС‹Р»СЊСЏ РЅРµ РєСЂРёС‚СѓСЋС‚
        ai.proc = false                       -- РѕС‚РєР»СЋС‡Р°РµРј РїСЂРѕРєРё
        ai:use_raw_damage()                   -- РёРіРЅРѕСЂРёСЂСѓРµРј РјРѕРґРёС„РёРєР°С‚РѕСЂС‹ СѓСЂРѕРЅР°
        ai:set_damage(dmg)                    -- РЅР°РЅРѕСЃРёРј "СЃС‹СЂРѕР№" СѓСЂРѕРЅ
    end
end)
