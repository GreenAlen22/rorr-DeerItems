local oWing = Object.new("DombraBerkutWings")
oWing:set_sprite(wingSprite)
Callback.add(oWing.on_create, function(self)
    self.timer       = 0
    self.image_speed = WING_ANIM_SPD   -- РїСЂРѕРёРіСЂС‹РІР°РµРј Р°РЅРёРјР°С†РёСЋ СЃРїСЂР°Р№С‚Р° (РЅР° 1-РєР°РґСЂРѕРІРѕРј вЂ” СЃС‚Р°С‚РёС‡РµРЅ)
    self.image_index = 0
    self.parent      = -4
    self:projectile_sync(8)
end)

Callback.add(oWing.on_step, function(self)
    self.timer = self.timer + 1

    -- Р”РµСЂР¶РёРјСЃСЏ Р·Р° СЃРїРёРЅРѕР№ РёРіСЂРѕРєР°, РїРѕРєР° РѕРЅ РґРІРёРіР°РµС‚СЃСЏ
    if Instance.exists(self.parent) then
        self.x     = self.parent.x
        self.y     = self.parent.y - WING_Y_OFFSET
        self.depth = self.parent.depth + 1   -- Р±РѕР»СЊС€Рµ depth = СЂРёСЃСѓРµС‚СЃСЏ Р—Рђ РёРіСЂРѕРєРѕРј
    end

    -- РџР»Р°РІРЅРѕРµ РїРѕСЏРІР»РµРЅРёРµ (РїРµСЂРІС‹Рµ 30%) Рё Р·Р°С‚СѓС…Р°РЅРёРµ (РѕСЃС‚Р°Р»СЊРЅРѕРµ)
    local t = self.timer / WING_LIFETIME
    if t < 0.3 then
        self.image_alpha = t / 0.3
    else
        self.image_alpha = 1 - (t - 0.3) / 0.7
    end

    if self.timer >= WING_LIFETIME then
        self:destroy()
    end
end)

